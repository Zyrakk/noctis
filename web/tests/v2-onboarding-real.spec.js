import {test,expect} from '@playwright/test'
const base=process.env.NOCTIS_ONBOARDING_URL
test('proyecto vacío → inventario actual → importar en pausa → política y activar',async({page})=>{
 test.skip(!base,'Requires isolated Go HTTPS/PostgreSQL onboarding runner')
 await page.goto(`${base}/v2/login`)
 await page.getByLabel('Username',{exact:true}).fill('fixture-admin')
 await page.getByLabel('Password',{exact:true}).fill('synthetic-only-long-password')
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await page.getByRole('link',{name:'Sources',exact:true}).click()
 await expect(page.getByText('No sources configured.',{exact:true})).toBeVisible()
 await expect(page.getByText(/No candidates/)).toBeVisible()
 expect((await page.request.post(`${base}/fixture/inventory`,{headers:{'X-Fixture-Token':process.env.NOCTIS_ONBOARDING_FIXTURE_TOKEN}})).status()).toBe(204)
 await page.reload()
 await expect(page.getByText('Canal privado sintético',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Import paused channel',exact:true}).click()
 await expect(page.getByRole('status').filter({hasText:'Channel imported'})).toBeVisible()
 await page.reload()
 const sourceRow=page.getByRole('listitem').filter({has:page.locator('strong').filter({hasText:'Canal privado sintético'})}).first()
 await expect(sourceRow).toContainText('Status: paused')
 await page.getByLabel('Priority intelligence requirement',{exact:true}).fill('PIR sintético explícito')
 await page.getByLabel('Monitoring term',{exact:true}).fill('synthetic')
 await page.getByRole('button',{name:'Create question and policy',exact:true}).click()
 await expect(page.getByRole('listitem').filter({hasText:'PIR sintético explícito'}).filter({has:page.getByRole('button',{name:'Pause question',exact:true})})).toBeVisible()
 const q=(await(await page.request.get(`${base}/api/v2/questions`)).json()).data[0]
 await sourceRow.getByText('Source policy and pause',{exact:true}).click()
 await sourceRow.getByLabel('PIR policy version').fill(`question:${q.id}`)
 await sourceRow.getByLabel('Collection authorized and active').check()
 await sourceRow.getByRole('button',{name:'Save source policy',exact:true}).click()
 await expect(sourceRow.getByRole('status')).toContainText('Policy and pause saved')
 await page.reload()
 const sources=(await(await page.request.get(`${base}/api/v2/sources`)).json()).data
 expect(sources).toHaveLength(1)
 expect(sources[0].status).not.toBe('paused')
 const candidates=await(await page.request.get(`${base}/api/v2/telegram/candidates`)).text()
 expect(candidates).not.toContain('access_hash')
 expect(candidates).not.toContain('987654321')
})
