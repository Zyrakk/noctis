import {test,expect} from '@playwright/test'
const base=process.env.NOCTIS_ONBOARDING_URL
test('proyecto vacío → inventario actual → importar en pausa → política y activar',async({page})=>{
 test.skip(!base,'Requires isolated Go HTTPS/PostgreSQL onboarding runner')
 await page.goto(`${base}/v2/login`)
 await page.getByLabel('Usuario',{exact:true}).fill('fixture-admin')
 await page.getByLabel('Contraseña').fill('synthetic-only-long-password')
 await page.getByRole('button',{name:'Entrar',exact:true}).click()
 await page.getByRole('link',{name:'Fuentes',exact:true}).click()
 await expect(page.getByText('No hay fuentes configuradas.',{exact:true})).toBeVisible()
 await expect(page.getByText(/No hay candidatos/)).toBeVisible()
 expect((await page.request.post(`${base}/fixture/inventory`,{headers:{'X-Fixture-Token':process.env.NOCTIS_ONBOARDING_FIXTURE_TOKEN}})).status()).toBe(204)
 await page.reload()
 await expect(page.getByText('Canal privado sintético',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Importar canal en pausa',exact:true}).click()
 await expect(page.getByRole('status').filter({hasText:'Canal importado'})).toBeVisible()
 await page.reload()
 const sourceRow=page.getByRole('listitem').filter({has:page.locator('strong').filter({hasText:'Canal privado sintético'})}).first()
 await expect(sourceRow).toContainText('Estado: paused')
 await page.getByLabel('Pregunta PIR',{exact:true}).fill('PIR sintético explícito')
 await page.getByLabel('Término de vigilancia',{exact:true}).fill('synthetic')
 await page.getByRole('button',{name:'Crear pregunta y política',exact:true}).click()
 await expect(page.getByRole('listitem').filter({hasText:'PIR sintético explícito'}).filter({has:page.getByRole('button',{name:'Pausar pregunta',exact:true})})).toBeVisible()
 const q=(await(await page.request.get(`${base}/api/v2/questions`)).json()).data[0]
 await sourceRow.getByText('Política y pausa de fuente',{exact:true}).click()
 await sourceRow.getByLabel('Versión de política PIR').fill(`question:${q.id}`)
 await sourceRow.getByLabel('Captura autorizada y activa').check()
 await sourceRow.getByRole('button',{name:'Guardar política de fuente',exact:true}).click()
 await expect(sourceRow.getByRole('status')).toContainText('Política y pausa guardadas')
 await page.reload()
 const sources=(await(await page.request.get(`${base}/api/v2/sources`)).json()).data
 expect(sources).toHaveLength(1)
 expect(sources[0].status).not.toBe('paused')
 const candidates=await(await page.request.get(`${base}/api/v2/telegram/candidates`)).text()
 expect(candidates).not.toContain('access_hash')
 expect(candidates).not.toContain('987654321')
})
