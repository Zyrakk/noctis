import { test, expect } from '@playwright/test'
test.use({ignoreHTTPSErrors:true})
test('sesión HTTPS real, expediente y evidencia retenida',async({page})=>{
  test.skip(!process.env.NOCTIS_V2_E2E_URL,'Requiere harness local HTTPS real')
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto(`${process.env.NOCTIS_V2_E2E_URL}/v2/login`)
  await page.getByLabel('Usuario',{exact:true}).fill(process.env.NOCTIS_V2_E2E_USERNAME)
  await page.getByLabel('Contraseña').fill(process.env.NOCTIS_V2_E2E_PASSWORD)
  await page.getByRole('button',{name:'Entrar'}).click()
  await expect(page.getByRole('heading',{name:'Hoy',exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Expedientes',exact:true}).click()
  await page.getByRole('link',{name:'Aviso sintético de prueba',exact:true}).click()
  await page.getByRole('button',{name:'Abrir evidencia 1'}).first().click()
  await expect(page.getByRole('dialog')).toContainText('Fuente sintética local')
  await expect(page.locator('.v2-evidence pre')).toContainText('CVE-2026-12345')
  await expect(page.locator('mark')).not.toBeEmpty()
  await page.getByRole('button',{name:'Cerrar evidencia'}).click()
  expect(await page.evaluate(()=>({...localStorage,...sessionStorage}))).toEqual({})
  await page.getByRole('button',{name:'Salir'}).click()
  await expect(page.getByRole('heading',{name:'Noctis · Acceso privado'})).toBeVisible()
  expect(errors).toEqual([])
})
