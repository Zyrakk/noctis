import { test, expect } from '@playwright/test'
test.use({ignoreHTTPSErrors:true})
test('sesión HTTPS real, expediente y evidencia retenida',async({page})=>{
  test.skip(!process.env.NOCTIS_V2_E2E_URL,'Requiere harness local HTTPS real')
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto(`${process.env.NOCTIS_V2_E2E_URL}/v2/login`)
  await page.getByLabel('Username',{exact:true}).fill(process.env.NOCTIS_V2_E2E_USERNAME)
  await page.getByLabel('Password',{exact:true}).fill(process.env.NOCTIS_V2_E2E_PASSWORD)
  await page.getByRole('button',{name:'Sign in'}).click()
  await expect(page.getByRole('heading',{name:'Today',exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Case files',exact:true}).click()
  await page.getByRole('link',{name:'Aviso sintético de prueba',exact:true}).click()
  await page.getByRole('button',{name:'Open evidence 1'}).first().click()
  await expect(page.getByRole('dialog')).toContainText('Fuente sintética local')
  await expect(page.locator('.v2-evidence pre')).toContainText('CVE-2026-12345')
  await expect(page.locator('mark')).not.toBeEmpty()
  await page.getByRole('button',{name:'Close evidence'}).click()
  expect(await page.evaluate(()=>({...localStorage,...sessionStorage}))).toEqual({})
  await page.getByRole('button',{name:'Sign out'}).click()
  await expect(page.getByRole('heading',{name:'Welcome back'})).toBeVisible()
  expect(errors).toEqual([])
})
